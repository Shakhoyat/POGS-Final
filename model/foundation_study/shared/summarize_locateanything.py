"""One table from every scene's LocateAnything3D detection check. Reads JSON only.

    python summarize_locateanything.py

Reads  artefacts/<row>/<scene>/bench/locateanything_detect.json  (written by
bench_locateanything.py) and writes  artefacts/<row>/LOCATEANYTHING_DETECT.md.
"""

import argparse
import glob
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import study_config as cfg  # noqa: E402


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--row", default="01_locateanything_dinotxt")
    args = ap.parse_args()

    base = os.path.join(cfg.ARTEFACTS, args.row)
    order = list(cfg.SCENES_V1 + cfg.SCENES_V2 + cfg.SCENES_HANDLE + cfg.SCENES_CONTROL)
    found = {}
    for p in glob.glob(os.path.join(base, "*", "bench", "locateanything_detect.json")):
        found[p.split(os.sep)[-3]] = json.load(open(p))
    scenes = [s for s in order if s in found] + sorted(s for s in found if s not in order)
    if not scenes:
        print(f"no locateanything_detect.json under {base}")
        return 1

    lines = [
        f"# {args.row}: LocateAnything3D detection check, every scene", "",
        "*Generated by `summarize_locateanything.py` from each scene's "
        "`bench/locateanything_detect.json`; nothing is entered by hand.*", "",
        "LocateAnything3D outputs **2D boxes, not instance masks**, so this measures "
        "localisation and speed only. It cannot drive POGS as the detector without a "
        "box-to-mask step. IoU is against the box around the ground-truth object mask. "
        "Sampling settings are the model card's (temperature 0.7, top_p 0.9, "
        "repetition penalty 1.1), seed 0.", "",
        "| scene | prompt | frames | found (IoU>=0.5) | mean first-box IoU | precision "
        "| median s/detection | peak GPU MB | hit token cap |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for s in scenes:
        d = found[s]
        lines.append(
            f"| `{s}` | {d['prompt']} | {d['frames']} | {d['found_iou50']}/{d['scored']} "
            f"| {d.get('mean_first_box_iou', d.get('mean_best_iou'))} "
            f"| {d.get('mean_precision', 'n/a')} | {d['median_s']} | {d['peak_gpu_mb']:.0f} "
            f"| {d.get('frames_hit_token_cap', 'n/a')}/{d['frames']} |")
    lines += ["", f"{len(scenes)} scene(s) of {len(order)} in the study matrix."]
    out = os.path.join(base, "LOCATEANYTHING_DETECT.md")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print("\n".join(lines))
    print(f"\nwrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
